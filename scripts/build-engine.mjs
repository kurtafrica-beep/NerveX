// Turns src/redact/engine.src.js into src/redact/engineSource.ts, a string the
// app loads into the page (web) or a hidden WebView (Android).
// Run after editing the engine: node scripts/build-engine.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = fs.readFileSync(path.join(root, 'src/redact/engine.src.js'), 'utf8');
const out = `// Generated by scripts/build-engine.mjs from engine.src.js. Do not edit by hand.\nexport const ENGINE_JS = ${JSON.stringify(src)};\n`;
const dest = path.join(root, 'src/redact/engineSource.ts');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(dest) || fs.readFileSync(dest, 'utf8') !== out) {
    console.error('engineSource.ts is out of date. Run: node scripts/build-engine.mjs');
    process.exit(1);
  }
} else {
  fs.writeFileSync(dest, out);
}
